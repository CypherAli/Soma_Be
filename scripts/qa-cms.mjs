/** Isolated CMS HTTP checks with disposable catalog, users, and rows. */
import 'dotenv/config';
import 'reflect-metadata';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { randomUUID, randomBytes, createHash } from 'node:crypto';
import { writeFileSync, mkdirSync, unlinkSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
const require = createRequire(import.meta.url);
const { NestFactory } = require('@nestjs/core');
const { ValidationPipe } = require('@nestjs/common');
const { AppModule } = require('../dist/src/app.module.js');
const { PrismaService } = require('../dist/src/prisma/prisma.service.js');
if (process.argv.includes('--audit-catalog')) {
  const { ContentService } = require('../dist/src/content/content.service.js');
  const content = new ContentService({ siteAsset: { findUnique: async () => null } }, { get: () => undefined });
  const definitions = JSON.parse(readFileSync('resources/cms/catalog.json', 'utf8')).documents;
  const failures = [];
  for (const document of definitions) {
    try { await content.validate(document.id, document.payload); } catch (error) { failures.push({ id: document.id, error: error.message }); }
  }
  console.log(JSON.stringify({ checked: definitions.length, failures: failures.length, examples: failures.slice(0, 12) }));
  process.exit(failures.length ? 1 : 0);
}
const runId = randomUUID();
const id = `qa:cms:${runId}`;
const catalogPath = resolve('tmp', `cms-${runId}.json`);
mkdirSync(resolve('tmp'), { recursive: true });
writeFileSync(catalogPath, JSON.stringify({ documents: [{ id, title: 'CMS verification', category: 'interface', source: 'qa-only', payload: { value: { title: 'Original', href: '/nguoi' } } }], meshes: {}, atlasParts: [] }));
process.env.CMS_CATALOG_PATH = catalogPath;
const app = await NestFactory.create(AppModule, { logger: ['error'] });
app.setGlobalPrefix('api');
app.useGlobalPipes(new ValidationPipe({ whitelist: true, forbidNonWhitelisted: true, transform: true, transformOptions: { enableImplicitConversion: true } }));
const prisma = app.get(PrismaService);
const users = [];
const assets = [];
const previews = [];
const checks = [];
try {
  await app.listen(0, '127.0.0.1');
  const base = `${await app.getUrl()}/api`;
  const tokens = {};
  for (const role of ['user', 'editor', 'admin']) {
    const user = await prisma.user.create({ data: { name: `CMS QA ${role}`, email: `cms-${runId}-${role}@example.invalid`, role } });
    users.push(user.id);
    const token = randomBytes(32).toString('hex');
    await prisma.session.create({ data: { tokenHash: createHash('sha256').update(token).digest('hex'), expiresAt: new Date(Date.now() + 600000), userId: user.id } });
    tokens[role] = token;
  }
  const call = async (path, role, method = 'GET', body) => {
    const response = await fetch(`${base}${path}`, { method, headers: { ...(role ? { Authorization: `Bearer ${tokens[role]}` } : {}), ...(body ? { 'Content-Type': 'application/json' } : {}) }, body: body ? JSON.stringify(body) : undefined });
    return { status: response.status, body: await response.json() };
  };
  const endpoint = `/admin/content/${encodeURIComponent(id)}`;
  assert.equal((await call('/admin/content')).status, 401);
  assert.equal((await call('/admin/content', 'user')).status, 403);
  assert.equal((await call('/admin/content', 'editor')).status, 200);
  assert.equal((await call(`${endpoint}/publish`, 'editor', 'POST', { version: 0 })).status, 403);
  checks.push('authentication and editor/admin separation');
  const draft = { value: { title: 'Draft title', href: '/nguoi' } };
  assert.equal((await call(endpoint, 'editor', 'PUT', { version: 0, payload: draft })).status, 200);
  assert.equal((await call('/content/published')).body.rules.length, 0);
  const preview = await call(`${endpoint}/preview`, 'editor', 'POST', { version: 1 });
  assert.equal(preview.status, 201);
  previews.push(createHash('sha256').update(preview.body.token).digest('hex'));
  assert.equal((await call(`/content/preview/${preview.body.token}`)).body.documents[id].value.title, 'Draft title');
  assert.equal((await call('/content/preview/invalid')).status, 404);
  checks.push('draft isolation and capability preview');
  assert.equal((await call(endpoint, 'editor', 'PUT', { version: 0, payload: draft })).status, 409);
  assert.equal((await call(endpoint, 'editor', 'PUT', { version: 1, payload: { value: { title: 'Bad', href: 'javascript:alert(1)' } } })).status, 400);
  checks.push('stale writes and unsafe URLs rejected');
  assert.equal((await call(`${endpoint}/publish`, 'admin', 'POST', { version: 1 })).status, 201);
  assert.equal((await call('/content/published')).body.documents[id].value.title, 'Draft title');
  const laterDraft = { value: { title: 'Unpublished later draft', href: '/nguoi' } };
  assert.equal((await call(endpoint, 'editor', 'PUT', { version: 2, payload: laterDraft })).status, 200);
  assert.equal((await call('/content/published')).body.documents[id].value.title, 'Draft title');
  checks.push('publication reads the saved version and later drafts stay private');
  const history = (await call(`${endpoint}/history`, 'editor')).body;
  assert.ok(history.length >= 4);
  const original = history.find((revision) => revision.version === 0);
  assert.ok(original);
  assert.equal((await call(`${endpoint}/restore`, 'editor', 'POST', { version: 3, revisionId: original.id })).status, 201);
  assert.equal((await call(endpoint, 'editor')).body.draft.value.title, 'Original');
  assert.equal((await call('/content/published')).body.documents[id].value.title, 'Draft title');
  const revertPreview = await call(`${endpoint}/preview`, 'editor', 'POST', { version: 4 });
  previews.push(createHash('sha256').update(revertPreview.body.token).digest('hex'));
  const restoredPreview = (await call(`/content/preview/${revertPreview.body.token}`)).body;
  assert.equal(restoredPreview.schemaVersion, 2);
  assert.equal(restoredPreview.documents[id].value.title, 'Original');
  assert.equal(restoredPreview.rules.length, 0);
  assert.equal((await call(`${endpoint}/history/${original.id}`, 'editor')).body.payload.value.title, 'Original');
  checks.push('source restoration, revision inspection and document-scoped preview');
  const concurrent = await Promise.all([call(endpoint, 'editor', 'PUT', { version: 4, payload: draft }), call(endpoint, 'editor', 'PUT', { version: 4, payload: laterDraft })]);
  assert.deepEqual(concurrent.map((result) => result.status).sort(), [200, 409]);
  checks.push('concurrent updates produce exactly one winner');
  const image = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jZ1kAAAAASUVORK5CYII=', 'base64');
  const form = new FormData(); form.set('file', new Blob([image], { type: 'image/png' }), 'cms-qa.png');
  const upload = await fetch(`${base}/admin/content/assets`, { method: 'POST', headers: { Authorization: `Bearer ${tokens.editor}` }, body: form });
  assert.equal(upload.status, 201);
  const asset = await upload.json(); assets.push(asset.id);
  const download = await fetch(`${base}${asset.url.replace(/^\/api/, '')}`);
  assert.equal(download.headers.get('content-type'), 'image/png');
  assert.deepEqual(Buffer.from(await download.arrayBuffer()), image);
  checks.push('uploaded assets download as binary with the correct MIME type');
  assert.equal((await call(endpoint, 'editor', 'PUT', { version: 5, payload: { value: { title: 'Local uploaded image', href: `${base}/content/assets/${asset.id}` } } })).status, 200);
  const sourceCatalog = JSON.parse(readFileSync('resources/cms/catalog.json', 'utf8'));
  const modelPath = Object.keys(sourceCatalog.meshes)[0];
  const modelBytes = readFileSync(resolve('../Soma_Fe/public', `.${modelPath}`));
  const modelForm = new FormData(); modelForm.set('file', new Blob([modelBytes], { type: 'model/gltf-binary' }), 'cms-qa.glb');
  const modelUpload = await fetch(`${base}/admin/content/assets`, { method: 'POST', headers: { Authorization: `Bearer ${tokens.editor}` }, body: modelForm });
  assert.equal(modelUpload.status, 201);
  const modelAsset = await modelUpload.json(); assets.push(modelAsset.id);
  assert.ok(modelAsset.meshNames.length > 0);
  const modelDownload = await fetch(`${base}/content/assets/${modelAsset.id}`);
  assert.equal(modelDownload.headers.get('content-type'), 'model/gltf-binary');
  assert.equal(createHash('sha256').update(Buffer.from(await modelDownload.arrayBuffer())).digest('hex'), createHash('sha256').update(modelBytes).digest('hex'));
  checks.push('real GLB upload, verified nodes, binary download and localhost asset links');
  const libraryFixtures = Array.from({ length: 101 }, (_, index) => ({ id: randomUUID(), filename: `qa-${runId}-${index}.png`, mime: 'image/png', bytes: image.length, data: image, meshNames: [], createdAt: new Date(Date.now() + index) }));
  assets.push(...libraryFixtures.map((item) => item.id));
  await prisma.siteAsset.createMany({ data: libraryFixtures });
  const library = await call('/admin/content/assets?q=cms-qa&kind=model&page=1', 'editor');
  assert.equal(library.status, 200);
  assert.ok(library.body.items.some((item) => item.id === modelAsset.id));
  assert.equal(library.body.pageSize, 24);
  assert.ok((await call('/admin/content/models', 'editor')).body.some((item) => item.url.endsWith(modelAsset.id)));
  const secondPage = (await call(`/admin/content/assets?q=${runId}&page=2`, 'editor')).body;
  assert.equal(secondPage.total, 101);
  assert.equal(secondPage.items.length, 24);
  assert.equal((await call('/admin/content/assets?page=-1', 'editor')).status, 400);
  checks.push('searchable paginated assets and model discovery beyond 100 uploads');
  assert.ok(await prisma.auditLog.count({ where: { actorId: { in: users }, entity: 'site_content' } }) >= 5);
  checks.push('content changes and publications have transactional audit records');
  console.log(JSON.stringify({ passed: checks.length, checks }));
} finally {
  await prisma.siteContentPreview.deleteMany({ where: { tokenHash: { in: previews } } });
  await prisma.siteContent.deleteMany({ where: { id } });
  await prisma.siteAsset.deleteMany({ where: { id: { in: assets } } });
  await prisma.auditLog.deleteMany({ where: { actorId: { in: users } } });
  await prisma.user.deleteMany({ where: { id: { in: users } } });
  await app.close();
  unlinkSync(catalogPath);
}
